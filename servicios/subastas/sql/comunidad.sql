-- SIDONIA · Anuncios de la comunidad (los que pone cada dueño, sin gestión de venta): el primero de cada persona es
-- gratis un mes; después, cada anuncio se paga por meses, con un precio que depende de cuántos tenga a la vez
-- (panel › Anuncios › Cobros › Tarifa). Aquí queda cada pago: el histórico de lo que se ha gastado cada uno.
-- Pégalo en Supabase › SQL Editor y ejecútalo (se puede repetir sin problema). Necesita sql/circulo.sql antes.

-- Hasta cuándo está pagado (o gratis) cada anuncio; vacío = por cobrar
alter table anuncios add column if not exists caduca timestamptz;
alter table anuncios add column if not exists gratis boolean not null default false;   -- el periodo actual es el mes gratis

create table if not exists pagos (
  id        bigint generated by default as identity primary key,
  cliente   text not null default '',                 -- id del cliente de Shopify (el anunciante)
  anuncio   bigint,                                   -- anuncios.id
  titulo    text not null default '',
  nombre    text not null default '',
  email     text not null default '',
  concepto  text not null default 'renovacion' check (concepto in ('gratis', 'alta', 'renovacion', 'otro')),
  meses     integer not null default 1,
  importe   numeric(10, 2) not null default 0,        -- euros cobrados (0 el mes gratis)
  metodo    text not null default '',                 -- bizum · transferencia · tarjeta · efectivo
  fecha     date not null default current_date,       -- cuándo se cobró
  desde     timestamptz,
  hasta     timestamptz,                              -- lo que cubre
  nota      text not null default '',
  creado    timestamptz not null default now()
);
create index if not exists pagos_cliente on pagos (cliente);
create index if not exists pagos_anuncio on pagos (anuncio);
create index if not exists pagos_fecha on pagos (fecha desc);
alter table pagos enable row level security;

-- Ajustes del panel (la tarifa)
create table if not exists ajustes (
  clave        text primary key,
  valor        jsonb not null default '{}'::jsonb,
  actualizado  timestamptz not null default now()
);
alter table ajustes enable row level security;

-- Los que ya están publicados al empezar a cobrar: un mes gratis desde hoy (para que nadie caduque de golpe)
with nuevos as (
  update anuncios set caduca = now() + interval '1 month', gratis = true
   where caduca is null and estado = 'publicado'
  returning id, cliente, titulo, vendedor_nombre, email, caduca
)
insert into pagos (cliente, anuncio, titulo, nombre, email, concepto, meses, importe, desde, hasta, nota)
select cliente, id, titulo, vendedor_nombre, email, 'gratis', 1, 0, now(), caduca, 'Mes gratis al empezar a cobrar' from nuevos;

