-- SIDONIA · Opiniones de los profesionales (página «Profesionales»): lo que cuenta la comunidad de cada taller.
-- Una opinión por persona y profesional (si vuelve a opinar, se cambia la suya). El equipo puede ocultar una desde
-- el panel › Clientes › Opiniones. Se puede ejecutar varias veces.
create table if not exists opiniones_pro (
  id          bigint generated by default as identity primary key,
  pro         text not null,                          -- el identificador del profesional en la web (cochera, talleres-gordillo…)
  cliente     text not null,                          -- id del cliente de Shopify
  nombre      text not null default '',               -- cómo firma («Lucía M.»)
  nota        int  not null check (nota between 1 and 5),
  texto       text not null default '',
  servicio    text not null default '',               -- qué le hicieron
  coche       text not null default '',               -- a qué coche o moto
  visible     boolean not null default true,
  creado      timestamptz not null default now(),
  actualizado timestamptz not null default now(),
  unique (pro, cliente)
);
create index if not exists opiniones_pro_pro on opiniones_pro (pro, visible, creado desc);
alter table opiniones_pro enable row level security;
notify pgrst, 'reload schema';
