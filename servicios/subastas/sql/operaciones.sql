-- SIDONIA · Centro operativo (panel › Ventas): cada coche, moto, barco o casa que vende Sidonia, con su propietario,
-- su comprador, el precio, la comisión y las fechas. Se rellena a mano en el panel o importando el Excel de ventas.
-- Se puede ejecutar varias veces.

create table if not exists operaciones (
  id                   bigint generated by default as identity primary key,
  tipo                 text not null default 'coche',          -- coche · moto · barco · casa · otro
  titulo               text not null,                          -- «PORSCHE 911 CARRERA 3.2 COUPÉ 1986»
  handle               text,                                   -- su ficha en la tienda (si la tiene)
  estado               text not null default 'en_venta',       -- captacion · en_venta · reservado · vendido · retirado
  modalidad            text not null default 'gestion',        -- gestion (venta gestionada) · encargo · subasta · particular
  propietario_nombre   text,
  propietario_email    text,
  propietario_telefono text,
  comprador_nombre     text,
  comprador_email      text,
  comprador_telefono   text,
  precio_anunciado     numeric,                                -- el precio de salida
  precio_venta         numeric,                                -- por cuánto se vendió
  comision             numeric,                                -- comisión de Sidonia (€)
  comision_comercial   numeric,                                -- lo que se lleva el comercial (€)
  comercial            text,
  fecha_alta           date,                                   -- cuándo se anunció
  fecha_venta          date,
  notas                text,
  origen               text not null default 'panel',          -- panel · excel
  ref                  text,                                   -- excel: de qué fila viene (para ponerla al día al volver a importar)
  creado               timestamptz not null default now(),
  actualizado          timestamptz not null default now()
);
create index if not exists operaciones_estado on operaciones (estado);
create index if not exists operaciones_handle on operaciones (handle);
alter table operaciones add column if not exists ref text;
create index if not exists operaciones_ref on operaciones (ref);
alter table operaciones enable row level security;

-- Entrar en el panel con el código: los intentos (para bloquear a quien pruebe códigos)
create table if not exists panel_intentos (
  id      bigint generated by default as identity primary key,
  ip      text not null default '',
  ok      boolean not null default false,
  creado  timestamptz not null default now()
);
create index if not exists panel_intentos_creado on panel_intentos (creado desc);
alter table panel_intentos enable row level security;
notify pgrst, 'reload schema';
