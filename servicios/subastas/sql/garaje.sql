-- SIDONIA · Mi garaje: los coches y motos de cada persona, aunque no los venda (lib/garaje.mjs), sus «me gusta» y lo
-- que se añade a su perfil (ciudad, Instagram, foto de portada y qué quiere recibir). Se puede ejecutar varias veces.
create table if not exists garaje (
  id             bigint generated by default as identity primary key,
  cliente        text not null,                       -- id del cliente de Shopify
  tipo           text not null default 'coche' check (tipo in ('coche', 'moto')),
  marca          text not null default '',
  modelo         text not null default '',
  anio           int,
  apodo          text not null default '',            -- cómo lo llama («La Abuela», «El Rojo»…)
  historia       text not null default '',
  mods           text not null default '',            -- lo que le ha hecho
  fotos          jsonb not null default '[]'::jsonb,  -- rutas en el cubo «anuncios» (la primera, la portada)
  alquiler       boolean not null default false,      -- lo alquilaría (próximamente)
  alquiler_como  text not null default '',            -- con · sin · igual (conductor)
  visible        boolean not null default true,       -- se ve en su garaje público
  likes          int not null default 0,
  creado         timestamptz not null default now(),
  actualizado    timestamptz not null default now()
);
create index if not exists garaje_cliente on garaje (cliente, creado desc);
create index if not exists garaje_recientes on garaje (visible, creado desc);
alter table garaje enable row level security;

create table if not exists garaje_likes (
  coche    bigint not null references garaje (id) on delete cascade,
  cliente  text not null,
  creado   timestamptz not null default now(),
  primary key (coche, cliente)
);
alter table garaje_likes enable row level security;

-- El perfil: ciudad, Instagram, foto de portada y qué quiere recibir { eventos, tienda, coches }
alter table perfiles add column if not exists ciudad text not null default '';
alter table perfiles add column if not exists instagram text not null default '';
alter table perfiles add column if not exists portada text not null default '';
alter table perfiles add column if not exists avisos jsonb not null default '{}'::jsonb;

