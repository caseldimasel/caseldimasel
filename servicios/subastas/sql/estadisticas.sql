-- SIDONIA · Estadísticas de la web (panel › Estadísticas). Se puede ejecutar varias veces.
-- La web (snippets/sidonia-estadisticas.liquid del tema) apunta lo que pasa: visitas, fichas vistas, contactos, me gusta,
-- compartidos, búsquedas, alertas y ofertas. Sin datos personales: un número al azar por navegador («sesion») y, si ha
-- iniciado sesión, su id de cliente de Shopify.

create table if not exists eventos (
  id       bigint generated by default as identity primary key,
  tipo     text not null,          -- visita · vista · contacto · like · unlike · compartir · busqueda · alerta · oferta
  handle   text,                   -- el anuncio (si va de un anuncio)
  titulo   text,
  canal    text,                   -- contacto: whatsapp · llamar · email · registro (le pedimos la cuenta antes)
  q        text,                   -- búsqueda: lo que ha escrito
  sesion   text,                   -- el navegador (al azar), para contar personas
  cliente  text,                   -- id del cliente de Shopify, si ha entrado con su cuenta
  app      boolean not null default false,   -- desde la app
  movil    boolean not null default false,   -- desde un móvil
  origen   text,                   -- visita: de dónde viene (instagram, google, whatsapp…)
  creado   timestamptz not null default now()
);
create index if not exists eventos_creado on eventos (creado desc);
create index if not exists eventos_handle on eventos (handle, tipo);
alter table eventos enable row level security;

create or replace function sidonia_evento(p jsonb) returns jsonb language sql as $$
  with i as (
    insert into eventos (tipo, handle, titulo, canal, q, sesion, cliente, app, movil, origen)
    select p->>'tipo', left(nullif(p->>'handle', ''), 160), left(nullif(p->>'titulo', ''), 160), left(nullif(p->>'canal', ''), 20),
           left(nullif(lower(trim(p->>'q')), ''), 80), left(nullif(p->>'sesion', ''), 40), left(nullif(p->>'cliente', ''), 20),
           coalesce((p->>'app')::boolean, false), coalesce((p->>'movil')::boolean, false), left(nullif(lower(p->>'origen'), ''), 40)
     where p->>'tipo' in ('visita', 'vista', 'contacto', 'like', 'unlike', 'compartir', 'busqueda', 'alerta', 'oferta')
    returning 1)
  select jsonb_build_object('ok', exists (select 1 from i))
$$;

-- Todo el panel de una vez: los últimos p_dias días (y los p_dias de antes, para comparar)
create or replace function sidonia_estadisticas(p_dias integer default 30) returns jsonb language sql stable as $$
  with
  r as (select now() - make_interval(days => greatest(1, least(p_dias, 365))) as desde,
               now() - 2 * make_interval(days => greatest(1, least(p_dias, 365))) as antes),
  e as (select ev.*, ev.creado >= r.desde as actual from eventos ev, r where ev.creado >= r.antes),
  a as (select * from e where actual),
  kpi as (
    select actual,
      count(distinct sesion) as visitantes,
      count(*) filter (where tipo = 'vista') as vistas,
      count(*) filter (where tipo = 'contacto' and canal is distinct from 'registro') as contactos,
      count(*) filter (where tipo = 'contacto' and canal = 'registro') as contactos_registro,
      count(*) filter (where tipo = 'like') as likes,
      count(*) filter (where tipo = 'compartir') as compartidos,
      count(*) filter (where tipo = 'busqueda') as busquedas,
      count(*) filter (where tipo = 'alerta') as alertas,
      count(*) filter (where tipo = 'oferta') as ofertas
    from e group by actual),
  dias as (
    select (creado at time zone 'Europe/Madrid')::date as dia, count(distinct sesion) as visitantes,
           count(*) filter (where tipo = 'vista') as vistas,
           count(*) filter (where tipo = 'contacto' and canal is distinct from 'registro') as contactos
      from a group by 1),
  serie as (
    select g::date as dia from r, generate_series((r.desde at time zone 'Europe/Madrid')::date, (now() at time zone 'Europe/Madrid')::date, interval '1 day') g),
  -- Guardados ahora: me gusta menos «ya no me gusta», desde siempre
  guardados as (
    select handle, greatest(0, count(*) filter (where tipo = 'like') - count(*) filter (where tipo = 'unlike')) as n
      from eventos where tipo in ('like', 'unlike') and handle is not null group by handle),
  anuncios as (
    select a.handle, max(a.titulo) as titulo,
      count(*) filter (where tipo = 'vista') as vistas,
      count(distinct sesion) filter (where tipo = 'vista') as personas,
      count(*) filter (where tipo = 'like') as likes,
      count(*) filter (where tipo = 'contacto' and canal is distinct from 'registro') as contactos,
      count(*) filter (where tipo = 'contacto' and canal = 'registro') as contactos_registro,
      count(*) filter (where tipo = 'compartir') as compartidos,
      count(*) filter (where tipo = 'oferta') as ofertas
    from a where a.handle is not null group by a.handle)
  select jsonb_build_object(
    'dias', greatest(1, least(p_dias, 365)),
    'actual', coalesce((select to_jsonb(k) - 'actual' from kpi k where actual), '{}'::jsonb),
    'anterior', coalesce((select to_jsonb(k) - 'actual' from kpi k where not actual), '{}'::jsonb),
    'registros', (select count(*) from clientes, r where primera >= r.desde),
    'registros_antes', (select count(*) from clientes, r where primera >= r.antes and primera < r.desde),
    'por_dia', coalesce((select jsonb_agg(jsonb_build_object('dia', s.dia, 'visitantes', coalesce(d.visitantes, 0), 'vistas', coalesce(d.vistas, 0), 'contactos', coalesce(d.contactos, 0)) order by s.dia)
                           from serie s left join dias d on d.dia = s.dia), '[]'::jsonb),
    'anuncios', coalesce((select jsonb_agg(to_jsonb(x) order by x.vistas desc, x.contactos desc) from (
                   select an.*, coalesce(g.n, 0) as guardados from anuncios an left join guardados g using (handle)
                    order by an.vistas desc, an.contactos desc limit 30) x), '[]'::jsonb),
    'mas_contactados', coalesce((select jsonb_agg(to_jsonb(x) order by x.contactos desc) from (
                   select handle, titulo, contactos, vistas from anuncios where contactos > 0 order by contactos desc, vistas desc limit 10) x), '[]'::jsonb),
    'mas_guardados', coalesce((select jsonb_agg(to_jsonb(x) order by x.n desc) from (
                   select g.handle, (select max(titulo) from eventos t where t.handle = g.handle) as titulo, g.n from guardados g where g.n > 0 order by g.n desc limit 10) x), '[]'::jsonb),
    'busquedas', coalesce((select jsonb_agg(to_jsonb(x) order by x.n desc) from (
                   select q, count(*) as n from a where tipo = 'busqueda' and q is not null group by q order by n desc limit 20) x), '[]'::jsonb),
    'canales', coalesce((select jsonb_object_agg(coalesce(canal, 'otro'), n) from (
                   select canal, count(*) as n from a where tipo = 'contacto' group by canal) x), '{}'::jsonb),
    'origenes', coalesce((select jsonb_agg(to_jsonb(x) order by x.n desc) from (
                   select coalesce(origen, 'directo') as origen, count(*) as n from a where tipo = 'visita' group by 1 order by n desc limit 12) x), '[]'::jsonb),
    'app', (select count(distinct sesion) from a where app),
    'movil', (select count(distinct sesion) from a where movil),
    'con_cuenta', (select count(distinct sesion) from a where cliente is not null)
  )
$$;

-- Solo para el servidor (clave de servicio)
revoke execute on function sidonia_evento(jsonb), sidonia_estadisticas(integer) from public;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke execute on function sidonia_evento(jsonb), sidonia_estadisticas(integer) from anon, authenticated';
  end if;
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    execute 'grant execute on function sidonia_evento(jsonb), sidonia_estadisticas(integer) to service_role';
  end if;
end $$;
notify pgrst, 'reload schema';
