-- SIDONIA · Valoraciones de precio con IA (lib/valoracion.mjs): la horquilla que se da a quien va a vender (en el
-- formulario «Publicar») y la que pide el equipo en el panel. Sirve para no repetir la misma búsqueda (si nada ha
-- cambiado, la de los últimos días) y para el límite diario por persona. Se puede ejecutar varias veces.
create table if not exists valoraciones (
  id         bigint generated by default as identity primary key,
  anuncio    bigint,                                -- anuncios.id (si ya es un anuncio)
  cliente    text not null default '',              -- id del cliente de Shopify (las de la web)
  origen     text not null default 'panel',         -- panel · web
  huella     text not null,                         -- lo que se valoró, resumido: lo mismo = la misma valoración
  entrada    jsonb not null default '{}'::jsonb,    -- tipo, título, ficha, estado… lo que se le pasó a la IA
  resultado  jsonb not null,                        -- { minimo, maximo, recomendado, venta_rapida, comparables, … }
  uso        jsonb not null default '{}'::jsonb,    -- tokens y búsquedas (lo que ha costado)
  creado     timestamptz not null default now()
);
create index if not exists valoraciones_huella on valoraciones (huella, creado desc);
create index if not exists valoraciones_anuncio on valoraciones (anuncio, creado desc);
create index if not exists valoraciones_cliente on valoraciones (cliente, creado desc);
create index if not exists valoraciones_creado on valoraciones (creado desc);
alter table valoraciones enable row level security;
notify pgrst, 'reload schema';
