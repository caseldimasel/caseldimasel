-- SIDONIA · Alquiler entre la comunidad, como Airbnb: anuncio con precio y calendario (en garaje), reservas que el dueño
-- acepta o rechaza en 24 h (o reserva inmediata), mensajes dentro de Sidonia y reseñas de los dos lados.
-- Antes: sql/garaje.sql y sql/alquiler.sql. Se puede ejecutar varias veces.
alter table garaje add column if not exists alq      jsonb not null default '{}'::jsonb;  -- precio/día, fianza, km, conductor, ciudad, entrega, normas, inmediata, mínimo…
alter table garaje add column if not exists bloqueos jsonb not null default '[]'::jsonb;  -- [["2027-06-01","2027-06-03"], …] días que no lo alquila

create table if not exists reservas (
  id          bigint generated by default as identity primary key,
  coche_id    bigint not null references garaje (id) on delete cascade,
  dueno       text not null,                 -- cliente de Shopify del dueño
  cliente     text not null,                 -- cliente de Shopify de quien alquila
  desde       date not null,
  hasta       date not null,                 -- último día (incluido)
  dias        int  not null,
  precio_dia  int  not null,
  total       int  not null,
  estado      text not null default 'pendiente', -- pendiente · aceptada · rechazada · cancelada (caducada y completada se calculan)
  conductor   text not null default '',
  para        text not null default '',
  mensaje     text not null default '',
  nombre      text not null default '',      -- de quien alquila
  email       text not null default '',
  telefono    text not null default '',
  respondida  timestamptz,
  creado      timestamptz not null default now()
);
create index if not exists reservas_coche on reservas (coche_id, estado);
create index if not exists reservas_cliente on reservas (cliente, creado desc);
create index if not exists reservas_dueno on reservas (dueno, creado desc);
alter table reservas enable row level security;

create table if not exists reservas_mensajes (
  id         bigint generated by default as identity primary key,
  reserva_id bigint not null references reservas (id) on delete cascade,
  de         text not null,                  -- cliente que escribe
  texto      text not null,
  creado     timestamptz not null default now()
);
create index if not exists reservas_mensajes_r on reservas_mensajes (reserva_id, creado);
alter table reservas_mensajes enable row level security;

create table if not exists reservas_resenas (
  id         bigint generated by default as identity primary key,
  reserva_id bigint not null references reservas (id) on delete cascade,
  coche_id   bigint not null,
  rol        text not null check (rol in ('huesped','anfitrion')),  -- quien escribe: huesped (sobre el coche y su dueño) · anfitrion (sobre quien alquiló)
  autor      text not null,
  sobre      text not null,
  nombre     text not null default '',
  nota       int  not null check (nota between 1 and 5),
  texto      text not null default '',
  creado     timestamptz not null default now(),
  unique (reserva_id, rol)
);
create index if not exists reservas_resenas_coche on reservas_resenas (coche_id, creado desc);
alter table reservas_resenas enable row level security;
notify pgrst, 'reload schema';

-- Sidonia hace de intermediario: cobra la reserva (precio + tarifa de servicio) y paga al dueño después
alter table reservas add column if not exists tarifa        int  not null default 0;   -- tarifa de servicio de Sidonia (€)
alter table reservas add column if not exists pago          text not null default '';  -- '' (se paga en la entrega) · pendiente · pagado
alter table reservas add column if not exists stripe_sesion text not null default '';
alter table reservas add column if not exists pagado        timestamptz;
alter table reservas add column if not exists pagado_dueno  timestamptz;               -- cuándo le pagasteis al dueño
notify pgrst, 'reload schema';
