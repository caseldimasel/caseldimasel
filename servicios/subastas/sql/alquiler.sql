-- SIDONIA · Alquiler (próximamente): la lista de espera de «Alquila un coche con alma». Quien quiere alquilar un coche
-- y quien quiere poner el suyo. Se ve en el panel › Clientes › Alquiler. Se puede ejecutar varias veces.
create table if not exists alquiler (
  id         bigint generated by default as identity primary key,
  rol        text not null default 'alquilar',  -- alquilar · poner
  cliente    text not null default '',          -- id del cliente de Shopify (si ha entrado)
  nombre     text not null default '',
  email      text not null default '',
  telefono   text not null default '',
  ciudad     text not null default '',
  para       text not null default '',          -- boda · rodaje · finde · ruta · otro
  fecha      text not null default '',
  conductor  text not null default '',          -- con · sin · igual
  coche      text not null default '',          -- el suyo, si lo pone
  mensaje    text not null default '',
  creado     timestamptz not null default now()
);
create index if not exists alquiler_creado on alquiler (creado desc);
create index if not exists alquiler_email on alquiler (email, creado desc);
alter table alquiler enable row level security;
notify pgrst, 'reload schema';

-- Peticiones públicas («Lo que busca la gente», sin datos personales) y los contactos entre quien busca y quien tiene el coche
alter table alquiler add column if not exists busca   text    not null default '';     -- «Un clásico rojo descapotable»
alter table alquiler add column if not exists publico boolean not null default false;  -- se ve en la web (sin nombre ni email)
alter table alquiler add column if not exists estado  text    not null default 'abierta'; -- abierta · cerrada
create table if not exists alquiler_contactos (
  id        bigint generated by default as identity primary key,
  tipo      text not null,                 -- tengo (un dueño contesta a una petición) · interes (alguien quiere alquilar un coche)
  peticion  bigint,                        -- alquiler.id (tengo)
  coche_id  bigint,                        -- garaje.id (interes)
  cliente   text not null default '',
  nombre    text not null default '',
  email     text not null default '',
  telefono  text not null default '',
  coche     text not null default '',
  fecha     text not null default '',
  mensaje   text not null default '',
  creado    timestamptz not null default now()
);
create index if not exists alquiler_contactos_creado on alquiler_contactos (creado desc);
alter table alquiler_contactos enable row level security;
notify pgrst, 'reload schema';

-- Peticiones con fotos de cómo se imagina el coche (hasta 3 rutas del almacén de fotos)
alter table alquiler add column if not exists fotos jsonb not null default '[]'::jsonb;
notify pgrst, 'reload schema';
