-- SIDONIA · Mensajes dentro de Sidonia: entre quien pregunta y el dueño de un coche en venta (comunidad), de un coche
-- en alquiler o de una petición («Busco un clásico rojo…»). Nadie ve el teléfono del otro: se hablan aquí y les llega
-- un aviso por email. Se puede ejecutar varias veces.
create table if not exists chats (
  id          bigint generated by default as identity primary key,
  tipo        text not null check (tipo in ('venta','alquiler','peticion')),
  ref         text not null,                 -- venta: id del anuncio · alquiler: id del coche (garaje) · peticion: id de la petición (alquiler)
  dueno       text not null,                 -- cliente de Shopify del dueño (del anuncio, del coche o de la petición)
  cliente     text not null,                 -- cliente de Shopify de quien escribe primero
  dueno_nombre   text not null default '',
  cliente_nombre text not null default '',
  cliente_email  text not null default '',
  titulo      text not null default '',
  foto        text not null default '',
  url         text not null default '',
  ultimo      text not null default '',
  ultimo_de   text not null default '',
  actualizado timestamptz not null default now(),
  leido_dueno   timestamptz,
  leido_cliente timestamptz,
  creado      timestamptz not null default now(),
  unique (tipo, ref, cliente)
);
create index if not exists chats_dueno on chats (dueno, actualizado desc);
create index if not exists chats_cliente on chats (cliente, actualizado desc);
alter table chats enable row level security;
create table if not exists chat_mensajes (
  id      bigint generated by default as identity primary key,
  chat_id bigint not null references chats (id) on delete cascade,
  de      text not null,
  texto   text not null,
  creado  timestamptz not null default now()
);
create index if not exists chat_mensajes_chat on chat_mensajes (chat_id, creado);
alter table chat_mensajes enable row level security;
notify pgrst, 'reload schema';
