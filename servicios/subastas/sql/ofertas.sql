-- SIDONIA · Ofertas de la web («Hacer una oferta» en cualquier anuncio): las de Sidonia (gestión de venta) y las de la
-- comunidad (le llegan directamente al dueño). Se ven en el panel › Ventas › Ofertas. Se puede ejecutar varias veces.
create table if not exists ofertas (
  id              bigint generated by default as identity primary key,
  handle          text not null,                   -- el anuncio en la tienda
  titulo          text not null default '',
  anuncio         bigint,                          -- anuncios.id si es de la comunidad
  para            text not null default 'sidonia', -- sidonia · dueno
  vendedor        text not null default '',
  vendedor_email  text not null default '',
  cliente         text not null default '',        -- id del cliente de Shopify del comprador (si ha entrado)
  nombre          text not null default '',
  email           text not null default '',
  telefono        text not null default '',
  oferta          numeric not null,
  precio          numeric,
  mensaje         text not null default '',
  enviada         boolean not null default false,  -- le ha llegado al vendedor por email
  creado          timestamptz not null default now()
);
create index if not exists ofertas_creado on ofertas (creado desc);
create index if not exists ofertas_cliente on ofertas (cliente, creado desc);
create index if not exists ofertas_handle on ofertas (handle);
alter table ofertas enable row level security;
notify pgrst, 'reload schema';
